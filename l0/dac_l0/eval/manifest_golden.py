"""Cross-language manifest V2 cases (pack/loader.py <-> android PackLoader.kt <-> Swift).

A fresh Ed25519 key is generated for every run and only its *public* key is written; the
private key never leaves this process. Each case carries the manifest bytes, the detached
signature, the device preconditions (trusted time, floors, revocation) and the verdict that
the Python loader produced and that the intended rule requires (asserted here).

  python -m dac_l0.eval.manifest_golden --out ../android/app/src/test/resources/golden_manifest_cases.txt
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Callable, Dict, List, Optional

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

from ..index.builder import build_index
from ..index.descriptors import DescriptorFamily
from ..pack.loader import DeviceRightsState, PackRejected, load_pack, parse_version
from ..pack.manifest import MANIFEST_V1, build_manifest, manifest_to_dict
from ..schemas import RegionAssuranceMethod
from ..synth.generator import Edition, EditionKind, gallery_works

PACK_ID = "L0-E2E"
NOW = "2026-10-10T12:00:00+00:00"


def _bundle():
    return build_index([Edition(w, EditionKind.THEATRICAL) for w in gallery_works(1)], DescriptorFamily.DACDHASH, 5.0)


def write(out: Path) -> None:
    priv = Ed25519PrivateKey.generate()
    pub = priv.public_key()
    raw = pub.public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    key_id = "DEVKEY-" + hashlib.sha256(raw).hexdigest()[:16]
    other = Ed25519PrivateKey.generate()
    b = _bundle()
    payload = b.to_bytes()
    base = manifest_to_dict(build_manifest(b, PACK_ID, "1.0.0", key_id, valid_from="2026-10-01T00:00:00+00:00"))
    base.pop("signature", None)
    base["manifest_type"] = "L0_DEV_INTEGRITY_MANIFEST_V2"

    lines = [
        "# golden_manifest_cases v1: manifest V2 (detached signature); generated by l0/dac_l0/eval/manifest_golden.py",
        f"PUBKEY {key_id} {raw.hex()}",
        f"PAYLOAD base {payload.hex()}",
    ]
    tampered_payload = bytearray(payload)
    tampered_payload[-3] ^= 1
    lines.append(f"PAYLOAD tampered {bytes(tampered_payload).hex()}")
    payloads = {"base": payload, "tampered": bytes(tampered_payload)}

    def case(name: str, expect: bool, edit: Optional[Callable[[Dict], None]] = None, now: Optional[str] = NOW,
             release: bool = False, floor_epoch: int = 0, floors: str = "-", revoked: bool = False,
             payload_name: str = "base", raw_edit: Optional[Callable[[bytes], bytes]] = None,
             signer: Optional[Ed25519PrivateKey] = None, sig_edit: Optional[Callable[[bytes], bytes]] = None,
             post_raw_edit: Optional[Callable[[bytes], bytes]] = None) -> None:
        m = json.loads(json.dumps(base))
        if edit:
            edit(m)
        data = json.dumps(m, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode("ascii")
        if raw_edit:
            data = raw_edit(data)
        sig = (signer or priv).sign(data)
        if sig_edit:
            sig = sig_edit(sig)
        if post_raw_edit:
            data = post_raw_edit(data)
        st = DeviceRightsState(minimum_rights_epoch=floor_epoch)
        st.trusted_keys[key_id] = pub
        if revoked:
            st.revoked_key_ids.add(key_id)
        if floors != "-":
            for item in floors.split(","):
                pid, v = item.split(":")
                st.minimum_pack_versions[pid] = parse_version(v, "floor")
        try:
            load_pack(data, payloads[payload_name], st, None if now is None else now, now is not None, release, signature=sig)
            got = True
        except PackRejected:
            got = False
        if got != expect:
            raise AssertionError(f"Python loader disagrees on {name}: expected {expect}, got {got}")
        lines.append(" ".join([
            "CASE", name, "ACCEPT" if expect else "REJECT", f"now={now or 'UNTRUSTED'}", f"release={int(release)}",
            f"epoch={floor_epoch}", f"floors={floors}", f"revoked={int(revoked)}", f"payload={payload_name}",
            f"manifest={data.hex()}", f"sig={sig.hex()}",
        ]))

    def setk(**kv):
        return lambda m: m.update(kv)

    lic = {"grant_id": "GRANT-LICENSED-001"}
    # ---- accepted
    case("valid_dev_no_expiry", True)
    case("valid_dev_untrusted_time_no_expiry", True, now=None)
    case("valid_dev_with_expiry", True, setk(valid_until="2027-01-01T00:00:00Z"))
    case("valid_until_offset_still_valid", True, setk(valid_until="2026-10-10T08:00:00-05:00"))   # 13:00Z
    case("valid_licensed_with_expiry", True, setk(valid_until="2027-01-01T00:00:00Z", **lic))
    case("release_licensed_calibrated", True, setk(valid_until="2027-01-01T00:00:00Z", calibration_status="CALIBRATED", **lic), release=True)
    case("version_numeric_order_2_10_over_2_9", True, setk(pack_version="2.10.0", minimum_allowed_version="2.0.0"), floors=f"{PACK_ID}:2.9.0")
    case("fractional_seconds_and_z", True, setk(valid_from="2026-10-01T00:00:00.5Z"))
    case("other_generator_version_is_provenance_only", True, setk(generator_version="licensed-ingest-7"))
    # ---- validity window
    case("future_valid_from", False, setk(valid_from="2026-11-01T00:00:00+00:00"))
    case("expired_by_offset_instant", False, setk(valid_until="2026-10-10T16:00:00+05:00"))    # 11:00Z
    case("valid_until_exclusive_equal_instant", False, setk(valid_until="2026-10-10T17:30:00+05:30"))
    case("inverted_window", False, setk(valid_from="2026-10-05T00:00:00Z", valid_until="2026-10-04T00:00:00Z"))
    case("empty_window", False, setk(valid_from="2026-10-05T00:00:00Z", valid_until="2026-10-05T00:00:00Z"))
    case("naive_valid_from", False, setk(valid_from="2026-10-01T00:00:00"))
    case("malformed_valid_from", False, setk(valid_from="yesterday"))
    case("month_13", False, setk(valid_from="2026-13-01T00:00:00Z"))
    case("missing_valid_from", False, setk(valid_from=None))
    case("date_only_valid_until", False, setk(valid_until="2027-01-01"))
    case("untrusted_time_with_expiry", False, setk(valid_until="2027-01-01T00:00:00Z"), now=None)
    case("licensed_untrusted_time", False, setk(valid_until="2027-01-01T00:00:00Z", **lic), now=None)
    case("licensed_without_expiry", False, setk(**lic))
    case("release_dev_pack", False, setk(valid_until="2027-01-01T00:00:00Z"), release=True)
    case("release_lab_calibration", False, setk(valid_until="2027-01-01T00:00:00Z", calibration_status="CALIBRATED_L0_SYNTHETIC", **lic), release=True)
    # ---- signature
    case("bad_signature_bit", False, sig_edit=lambda s: bytes([s[0] ^ 1]) + s[1:])
    case("signature_short", False, sig_edit=lambda s: s[:63])
    case("signed_by_other_key_same_key_id", False, signer=other)
    case("bytes_changed_after_signing", False, post_raw_edit=lambda d: d.replace(b'"pack_version":"1.0.0"', b'"pack_version":"1.0.1"', 1))
    case("revoked_signer", False, revoked=True)
    case("unknown_key_id", False, setk(key_id="DEVKEY-0000000000000000"))
    case("v1_manifest_type_with_detached_signature", False, setk(manifest_type=MANIFEST_V1))
    # ---- compatibility
    case("unknown_calibration_status", False, setk(calibration_status="PROBABLY_FINE"))
    case("dev_claims_release_calibration", False, setk(calibration_status="CALIBRATED"))
    case("empty_calibration_version", False, setk(calibration_version=""))
    case("family_mismatch", False, setk(descriptor_family="HASH64"))
    case("descriptor_bytes_mismatch", False, setk(descriptor_bytes=32))
    case("preprocessing_mismatch", False, setk(preprocessing_version="prep-640x360-gray-uniformcrop-3"))
    case("index_format_mismatch", False, setk(index_format_version="idx-flat-3"))
    case("sampling_interval_mismatch", False, setk(sampling_interval_s=2.0))
    case("indexed_hours_mismatch", False, setk(indexed_hours=1.0))
    case("title_count_mismatch", False, setk(title_count=2))
    case("vector_count_mismatch", False, setk(vector_count=1))
    case("payload_hash_mismatch", False, payload_name="tampered")
    case("payload_size_mismatch", False, setk(payload_size_bytes=1))
    case("region_method_not_accepted", False, setk(region_assurance_method=RegionAssuranceMethod.ONLINE_ACTIVATION.value))
    # ---- versions / epochs
    case("malformed_version", False, setk(pack_version="1.0"))
    case("leading_zero_version", False, setk(pack_version="01.0.0"))
    case("below_declared_minimum", False, setk(minimum_allowed_version="1.2.0"))
    case("rollback_below_device_floor", False, setk(pack_version="1.9.0", minimum_allowed_version="1.0.0"), floors=f"{PACK_ID}:2.0.0")
    case("epoch_rollback", False, setk(rights_epoch=3), floor_epoch=5)
    # ---- shape / strict JSON
    case("extra_key", False, setk(debug=True))
    case("missing_key", False, lambda m: m.pop("tombstones"))
    case("bad_pack_id", False, setk(pack_id="../evil"))
    case("bool_as_int", False, setk(rights_epoch=True))
    case("float_as_int", False, setk(title_count=1.0))
    case("duplicate_json_key", False, raw_edit=lambda d: d.replace(b'"title_count":1', b'"title_count":1,"title_count":1', 1))
    case("unknown_operation_grant", False, setk(operation_grants=["TRANSIENT_QUERY", "SELL"]))
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    write(Path(ap.parse_args(argv).out))
    print("ok")


if __name__ == "__main__":
    main()

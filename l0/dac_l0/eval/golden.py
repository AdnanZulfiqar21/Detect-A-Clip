"""Golden vectors for porting verification + decision to Kotlin/Swift (P04-T08 preparation).

Generates structured random cases (montages, series with shared footage, competing works,
edition ties, weak evidence) and records the Python reference outputs of `verify()` and
`decide()` in a line-based text format that the JVM/XCTest ports parse without a JSON
dependency. Deterministic for a given seed.

  python -m dac_l0.eval.golden --out ../android/app/src/test/resources/golden_recognition.txt
"""
from __future__ import annotations

import argparse
import random
from dataclasses import replace
from pathlib import Path
from typing import List, Tuple

import numpy as np

from ..decision import DecisionThresholds, FrameSummary, decide
from ..index.builder import IndexBundle, WorkEntry
from ..index.descriptors import DescriptorFamily, Locator
from ..index.retrieval import Candidate
from ..verify import verify

EDITIONS = ["E0_THEATRICAL", "E1_EXTENDED", "E2_BROADCAST"]


def _works() -> List[WorkEntry]:
    ws = [WorkEntry(i, f"SW{i:03d}", "t", list(EDITIONS), [60.0, 66.0, 52.0]) for i in range(5)]
    ws += [WorkEntry(5 + k, f"SW{100 + k:03d}", "t", ["E0_THEATRICAL"], [60.0], "S-G", f"E{k + 1:02d}") for k in range(3)]
    return ws


def _segment(rng: random.Random, work: int, edition: int, q0: int, q1: int, offset: int, dist_hi: float, jitter: int) -> List[Tuple[int, Candidate]]:
    out = []
    for qt in range(q0, q1, 500):
        if rng.random() < 0.85:
            t = max(0, qt + offset + rng.randint(-jitter, jitter))
            d = rng.choice([float(rng.randint(0, int(dist_hi))), round(rng.uniform(0, dist_hi) * 4) / 4])
            out.append((qt, Candidate(Locator(work, edition, t), d)))
    return out


def make_case(rng: random.Random, n_works: int):
    kind = rng.choice(["single", "single", "montage", "series_shared", "competing", "edition_tie", "noise", "weak"])
    per: dict = {qt: [] for qt in range(0, 8000, 500)}

    def add(items):
        for qt, c in items:
            per[qt].append(c)

    if kind in ("single", "weak"):
        w, e = rng.randrange(5), rng.randrange(3)
        lo, hi = (0, 8000) if kind == "single" else (rng.choice([0, 2000, 4000]), rng.choice([5000, 6500, 8000]))
        add(_segment(rng, w, e, lo, hi, rng.randrange(0, 50) * 1000, 9, 700))
    elif kind == "montage":
        a, b = rng.sample(range(5), 2)
        add(_segment(rng, a, 0, 0, 4000, rng.randrange(0, 40) * 1000, 8, 600))
        add(_segment(rng, b, 0, 4000, 8000, rng.randrange(0, 40) * 1000, 8, 600))
    elif kind == "series_shared":
        off = rng.randrange(0, 5) * 1000
        for ep in rng.sample(range(5, 8), rng.choice([2, 3])):
            add(_segment(rng, ep, 0, 0, 8000, off, 7, 500))
    elif kind == "competing":
        a, b = rng.sample(range(5), 2)
        add(_segment(rng, a, 0, 0, 8000, 10_000, 8, 500))
        add(_segment(rng, b, 0, 0, 8000, 30_000, 8, 500))
    elif kind == "edition_tie":
        w = rng.randrange(5)
        off = rng.randrange(0, 30) * 1000
        add(_segment(rng, w, 0, 0, 8000, off, 6, 400))
        add(_segment(rng, w, 1, 0, 8000, off, 6, 400))
    # background noise candidates
    for qt in per:
        for _ in range(rng.randint(0, 3)):
            per[qt].append(Candidate(Locator(rng.randrange(n_works), 0, rng.randrange(0, 60) * 1000), float(rng.randint(5, 9))))
    per_frame = [(qt, sorted(cs, key=lambda c: c.distance)[:12]) for qt, cs in sorted(per.items())]
    selected = 16
    qualified = rng.choice([16, 16, 14, 12, 8, 3, 0])
    unusable = 0 if qualified > 3 else rng.choice([0, 16 - qualified])
    return kind, per_frame, FrameSummary(offered=80, selected=selected, qualified=qualified, unusable_feed=unusable)


def _fmt_f(x: float) -> str:
    return repr(float(x))


def write(out: Path, n: int = 400, seed: int = 20261009) -> None:
    rng = random.Random(seed)
    works = _works()
    bundle = IndexBundle(DescriptorFamily.HASH64, 2.0, np.zeros((0, 8), np.uint8), np.zeros((0, 16), np.uint8), works)
    base = DecisionThresholds(hash_max_distance=9.0)
    variants = [base,
                replace(base, verified_min_support=8, verified_min_span_ms=4000, verified_min_margin=4, possible_min_span_ms=1500),
                replace(base, possible_on_competition=True, verified_min_support_fraction=0.6),
                replace(base, possible_max_mean_dist_frac=0.6, episode_margin=2)]
    L = ["# golden_recognition v1 — generated by l0/dac_l0/eval/golden.py; do not edit by hand",
         "WORKS " + str(len(works))]
    for w in works:
        L.append(f"W {w.work_index} {w.work_id} {w.series_id or '-'} {w.episode_id or '-'} {','.join(w.editions)}")
    for i in range(n):
        kind, per_frame, fs = make_case(rng, len(works))
        th = variants[i % len(variants)]
        hyps = verify(per_frame, 2000)
        r = decide("g", 1, hyps, fs, bundle, 0, th)
        L.append(f"CASE {i} {kind}")
        L.append(f"FRAMES {fs.selected} {fs.qualified} {fs.unusable_feed}")
        L.append("TH " + " ".join(str(v) for v in [
            th.min_qualified_frames, th.verified_min_support, _fmt_f(th.verified_min_support_fraction), th.verified_min_span_ms,
            _fmt_f(th.verified_max_mean_dist_frac), th.verified_min_margin, th.possible_min_support, th.possible_min_span_ms,
            _fmt_f(th.possible_max_mean_dist_frac), int(th.possible_on_competition), th.episode_margin, _fmt_f(th.hash_max_distance)]))
        for qt, cs in per_frame:
            L.append(f"PF {qt} " + (";".join(f"{c.locator.work_index}:{c.locator.edition_index}:{c.locator.t_ms}:{_fmt_f(c.distance)}" for c in cs) or "-"))
        for h in hyps:
            L.append(f"H {h.work_index} {-1 if h.edition_index is None else h.edition_index} {h.offset_ms} {h.support} "
                     f"{_fmt_f(h.mean_distance)} {h.query_start_ms} {h.query_end_ms} {','.join(map(str, h.ambiguous_editions)) or '-'}")
        segs = "|".join(f"{s.work_id}@{s.edition_id or '-'}@{s.query_start_ms}@{s.query_end_ms}@"
                        f"{'-' if s.reference_offset_ms is None else s.reference_offset_ms}@{s.supporting_frames}" for s in r.segments) or "-"
        L.append(f"R {r.state.value} {r.candidate_work_id or '-'} {r.candidate_edition_id or '-'} {r.candidate_episode_id or '-'} "
                 f"{','.join(r.ambiguity_flags) or '-'} {segs}")
        L.append("END")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")  # LF on every OS


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--n", type=int, default=400)
    a = ap.parse_args(argv)
    write(Path(a.out), a.n)
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()

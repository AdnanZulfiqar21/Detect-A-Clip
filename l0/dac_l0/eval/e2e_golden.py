"""End-to-end golden vectors for the device port: pack bytes → DAC-DHASH-v1 query hashing →
flat retrieval → temporal verification → decision (P04-T08 preparation).

Frames are generated in every language from the shared xorshift source (index/exact.py), so
no pixels are stored. The pack is written as hex text (no binary in the repository).

  python -m dac_l0.eval.e2e_golden --out ../android/app/src/test/resources/golden_e2e.txt
"""
from __future__ import annotations

import argparse
from dataclasses import replace
from pathlib import Path
from typing import List, Tuple

import numpy as np

from ..decision import DecisionThresholds, FrameSummary, decide
from ..index.builder import IndexBundle, WorkEntry
from ..index.descriptors import DescriptorFamily, Locator
from ..index.exact import content_frame, dac_dhash_v1
from ..index.retrieval import FlatRetriever
from ..verify import verify

W, H = 64, 36
REF_STEP_MS = 2000
DURATION_MS = 30_000

# work_index → (work_id, series, episode, seed base); episodes share their first 3 segments.
WORKS = [(0, "SW000", None, None, 1000), (1, "SW001", None, None, 2000), (2, "SW002", None, None, 3000),
         (3, "SW100", "S-E2E", "E01", 4000), (4, "SW101", "S-E2E", "E02", 5000)]
SHARED_INTRO_SEGMENTS = 3   # segments 0..2 (6 s) identical across the two episodes
INTRO_SEED_BASE = 9000


def segment_seed(work_index: int, t_ms: int) -> int:
    seg = t_ms // REF_STEP_MS
    w = WORKS[work_index]
    if w[2] is not None and seg < SHARED_INTRO_SEGMENTS:
        return INTRO_SEED_BASE + seg
    return w[4] + seg


def frame(seed: int, brightness: int) -> np.ndarray:
    f = content_frame(seed, W, H).astype(np.int16) + brightness
    return np.clip(f, 0, 255).astype(np.uint8)


def build_pack() -> IndexBundle:
    desc, locs, works = [], [], []
    for wi, wid, series, ep, _ in WORKS:
        works.append(WorkEntry(wi, wid, f"SYNTHETIC {wid}", ["E0_THEATRICAL"], [DURATION_MS / 1000], series, ep, {"en": f"Synthetic {wid}"}))
        for t in range(0, DURATION_MS, REF_STEP_MS):
            desc.append(dac_dhash_v1(frame(segment_seed(wi, t), 0)).to_bytes(8, "little"))
            locs.append(Locator(wi, 0, t).pack())
    d = np.frombuffer(b"".join(desc), np.uint8).reshape(-1, 8).copy()
    l = np.frombuffer(b"".join(locs), np.uint8).reshape(-1, 16).copy()
    b = IndexBundle(DescriptorFamily.DACDHASH, REF_STEP_MS / 1000, d, l, works)
    b.indexed_hours = len(desc) * REF_STEP_MS / 3_600_000
    return b


# Each query: list of (query_t_ms, work_index or -1 for an absent seed, source_t_ms, brightness)
def queries() -> List[Tuple[str, List[Tuple[int, int, int, int]]]]:
    q = []
    q.append(("single_SW001", [(t, 1, 10_000 + t, 0) for t in range(0, 8000, 500)]))
    q.append(("bright_SW002", [(t, 2, 4_000 + t, 6) for t in range(0, 8000, 500)]))
    q.append(("absent", [(t, -1, t, 0) for t in range(0, 8000, 500)]))
    q.append(("montage_SW000_SW002", [(t, 0 if t < 4000 else 2, (12_000 if t < 4000 else 20_000) + t, 0) for t in range(0, 8000, 500)]))
    q.append(("series_intro", [(t, 3, t, 0) for t in range(0, 6000, 500)]))
    q.append(("series_unique_E02", [(t, 4, 14_000 + t, 0) for t in range(0, 8000, 500)]))
    return q


def query_seed(work_index: int, src_t: int) -> int:
    return 777_000 + src_t // REF_STEP_MS if work_index < 0 else segment_seed(work_index, src_t)


def write(out: Path) -> None:
    b = build_pack()
    th = replace(DecisionThresholds(dacdhash_max_distance=9.0), mirror_invariant=False, top_k=12)
    retr = FlatRetriever(b)
    L = ["# golden_e2e v1 — generated by l0/dac_l0/eval/e2e_golden.py; do not edit by hand",
         "PACKHEX " + b.to_bytes().hex(),
         "TH " + " ".join(str(v) for v in [th.min_qualified_frames, th.verified_min_support, repr(th.verified_min_support_fraction),
                                          th.verified_min_span_ms, repr(th.verified_max_mean_dist_frac), th.verified_min_margin,
                                          th.possible_min_support, th.possible_min_span_ms, repr(th.possible_max_mean_dist_frac),
                                          int(th.possible_on_competition), th.episode_margin, repr(th.dacdhash_max_distance), th.top_k])]
    for name, frames in queries():
        per_frame = []
        L.append(f"Q {name} {len(frames)}")
        for qt, wi, src_t, bright in frames:
            seed = query_seed(wi, src_t)
            L.append(f"QF {qt} {seed} {bright}")
            hsh = dac_dhash_v1(frame(seed, bright))
            per_frame.append((qt, retr.search(hsh.to_bytes(8, "little"), top_k=th.top_k, max_distance=th.dacdhash_max_distance)))
        hyps = verify(per_frame, REF_STEP_MS)
        fs = FrameSummary(offered=len(frames), selected=len(frames), qualified=len(frames))
        r = decide("e2e", 1, hyps, fs, b, 0, th)
        segs = "|".join(f"{s.work_id}@{s.edition_id or '-'}@{s.query_start_ms}@{s.query_end_ms}@"
                        f"{'-' if s.reference_offset_ms is None else s.reference_offset_ms}@{s.supporting_frames}" for s in r.segments) or "-"
        L.append(f"R {r.state.value} {r.candidate_work_id or '-'} {r.candidate_edition_id or '-'} {r.candidate_episode_id or '-'} "
                 f"{','.join(r.ambiguity_flags) or '-'} {segs}")
    out.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    write(Path(ap.parse_args(argv).out))
    print("ok")


if __name__ == "__main__":
    main()

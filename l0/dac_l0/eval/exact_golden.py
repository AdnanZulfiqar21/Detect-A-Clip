"""Golden vectors for DAC-CROP-v1 / DAC-QUAL-v1 / mirrored DAC-DHASH-v1 (ED-17).

Frames are composed in every language from the shared xorshift content source: a content
block image of size (iw, ih) placed at (ox, oy) on a uniform canvas of value `bg`
(letterbox/pillarbox/PiP-like), or special cases (all black, single flat block). Records the
crop rectangle, the quality flag sequence over a short frame sequence, and both hashes.

  python -m dac_l0.eval.exact_golden --out ../android/app/src/test/resources/golden_exact.txt
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

from ..index.exact import content_frame, crop_rect, dhash_luma, luma_u8, quality_v1

W, H = 160, 90

# (case id, seed, iw, ih, ox, oy, bg, blocks_x, blocks_y)
CASES = [
    ("full", 11, 160, 90, 0, 0, 0, 16, 9),
    ("letterbox", 12, 160, 66, 0, 12, 0, 16, 9),
    ("pillarbox", 13, 120, 90, 20, 0, 0, 16, 9),
    ("pip_grey", 14, 96, 54, 32, 18, 235, 16, 9),
    ("pip_offcentre", 15, 80, 45, 70, 40, 128, 16, 9),
    ("tiny_content", 16, 40, 30, 60, 30, 0, 8, 6),
    ("flat_block", 17, 160, 90, 0, 0, 0, 1, 1),
    ("black", 0, 0, 0, 0, 0, 0, 1, 1),
    ("odd_size", 18, 157, 89, 1, 1, 30, 16, 9),
]


def compose(seed: int, iw: int, ih: int, ox: int, oy: int, bg: int, bx: int, by: int) -> np.ndarray:
    out = np.full((H, W, 3), bg, dtype=np.uint8)
    if iw > 0 and ih > 0:
        out[oy:oy + ih, ox:ox + iw] = content_frame(seed, iw, ih, bx, by)
    return out


def write(out: Path) -> None:
    L = ["# golden_exact v1 — DAC-CROP-v1 / DAC-QUAL-v1 / DAC-DHASH-v1 (mirrored); generated by l0/dac_l0/eval/exact_golden.py",
         f"SIZE {W} {H}"]
    for cid, seed, iw, ih, ox, oy, bg, bx, by in CASES:
        frames = [compose(seed, iw, ih, ox, oy, bg, bx, by), compose(seed, iw, ih, ox, oy, bg, bx, by),
                  compose(seed + 1000, iw, ih, ox, oy, bg, bx, by)]
        prev = None
        flags = []
        rects = []
        hashes = []
        for f in frames:
            y = luma_u8(f)
            t, b, l, r = crop_rect(y)
            reg = y[t:b, l:r]
            flag, means = quality_v1(reg, prev)
            if flag == "OK":
                prev = means
            flags.append(flag)
            rects.append(f"{t},{b},{l},{r}")
            hashes.append(f"{dhash_luma(reg):016x}:{dhash_luma(reg[:, ::-1]):016x}")
        L.append(f"C {cid} {seed} {iw} {ih} {ox} {oy} {bg} {bx} {by} {'/'.join(rects)} {'/'.join(flags)} {'/'.join(hashes)}")
    out.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    write(Path(ap.parse_args(argv).out))
    print("ok")


if __name__ == "__main__":
    main()
